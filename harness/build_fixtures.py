def oracle_expectations(payload):
    """Exact point-estimate expectations for every light in a payload."""
    d_near = payload["config"]["d_near"]
    out = {"semantic_lights": [], "mechanical_lights": []}
    for light in payload["lights"]:
        for key, target in (("semantic_specimens", "semantic_lights"),
                            ("mechanical_specimens", "mechanical_lights")):
            cells_list = [{c: s["cells"][c]["counts"] for c in CELLS}
                          for s in light[key]]
            truth = smp.light_truth(cells_list, d_near=d_near)
            entry = {
                "light_id": light["id"],
                "P0_bar": core.to_exact_string(truth["P0_bar"]),
                "I_P_bar": core.to_exact_string(truth["I_P_bar"]),
                "Q_bar": core.to_exact_string(truth["Q_bar"]),
                "specimens": [],
            }
            for specimen_input, metrics in zip(light[key], truth["specimens"]):
                entry["specimens"].append({
                    "id": specimen_input["id"],
                    "P0": core.to_exact_string(metrics["P0"]),
                    "PA": core.to_exact_string(metrics["PA"]),
                    "I_P": core.to_exact_string(metrics["I_P"]),
                    "W0": core.to_exact_string(metrics["W0"]),
                    "L0": core.to_exact_string(metrics["L0"]),
                    "T0": core.to_exact_string(metrics["T0"]),
                    "WA": core.to_exact_string(metrics["WA"]),
                    "LA": core.to_exact_string(metrics["LA"]),
                    "TA": core.to_exact_string(metrics["TA"]),
                    "delta0": core.to_exact_string(metrics["delta0"]),
                    "deltaA": core.to_exact_string(metrics["deltaA"]),
                    "I_delta": core.to_exact_string(metrics["I_delta"]),
                    "p_floor_A0": core.to_exact_string(metrics["p_floor_A0"]),
                    "K_A": core.to_exact_string(metrics["K_A"]),
                    "G": core.to_exact_string(metrics["G"]),
                    "K_Q": core.to_exact_string(metrics["K_Q"]),
                    "G_Q": core.to_exact_string(metrics["G_Q"]),
                    "Q": core.to_exact_string(metrics["Q"]),
                    "collision": {c: core.to_exact_string(metrics["collision"][c])
                                  for c in CELLS},
                    "degeneracy": dict(metrics["degeneracy"]),
                })
            out[target].append(entry)
    return out


STUDY_CANDIDATE_N = (8, 10, 12, 16, 20, 30)


def classify_n(payload):
    """Operator decision D5: separate study-candidate N from topology exercises.

    The class is COMPUTED from the payload's actual cell totals, never
    asserted, so a scenario cannot be mislabelled by an author oversight.
    """
    totals = set()
    for light in payload["lights"]:
        for key in ("semantic_specimens", "mechanical_specimens"):
            for specimen in light[key]:
                for cell in CELLS:
                    totals.add(sum(specimen["cells"][cell]["counts"]))
    outside = sorted(t for t in totals if t not in STUDY_CANDIDATE_N)
    if outside:
        return {
            "n_class": "TOPOLOGY_EXERCISE_ONLY_NOT_STUDY_EVIDENCE",
            "replicate_totals": sorted(totals),
            "totals_outside_candidate_set": outside,
            "study_candidate_N": list(STUDY_CANDIDATE_N),
            "usable_as_study_evidence": False,
            "rationale": (
                "Included only as a synthetic harness "
                "topology/branch-coverage. The registered 0.05 equivalence "
                "margins are not resolvable at study N under any "
                "distribution-free construction, which preregistration 3.4 "
                "anticipates, so some decision branches have no sound case at "
                "candidate N. This scenario is NOT evidence about study "
                "behaviour at any candidate N and plays no part in N "
                "selection; the coverage campaign is that evidence."),
        }
    return {
        "n_class": "STUDY_CANDIDATE_N",
        "replicate_totals": sorted(totals),
        "totals_outside_candidate_set": [],
        "study_candidate_N": list(STUDY_CANDIDATE_N),
        "usable_as_study_evidence": True,
        "rationale": "every cell total lies in the study candidate set",
    }


def scenario(scenario_id, description, payload, expected, strength,
             contract_refs, notes=None, family="clean", target="analyze"):
    entry = {
        "scenario_id": scenario_id,
        "family": family,
        "target": target,
        "description": description,
        "contract_refs": contract_refs,
        "assertion_strength": strength,
        "notes": notes or "",
        "payload": payload,
        "expected": expected,
        "oracle_point_expectations": oracle_expectations(payload),
    }
    entry["replicate_classification"] = classify_n(payload)
    return entry


def light_expect(c1, rng, c2, c4, a_l, light_ids=("L1", "L2", "L3")):
    return [{"light_id": lid, "c1": c1, "range": rng, "c2": c2, "c4": c4,
             "A_l": a_l} for lid in light_ids]


def mech_expect(c5, light_ids=("L1", "L2", "L3")):
    return [{"light_id": lid, "c5": c5} for lid in light_ids]


def cross_expect(a_all, a_vector=(True, True, True)):
    return {"A_all": a_all, "A_vector": list(a_vector),
            "c3": "WITHHELD_NOT_IMPLEMENTED", "pooled_verdict_absent": True}


