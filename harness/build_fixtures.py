def sep_high(n):
    """00 cell fully above the 0B cell: P0 = 1 (anchor A05)."""
    return point(10, n)


def sep_low(n):
    return point(1, n)


def dispersed_high(n):
    """00 cell spread over 7..10: P0 = 1 against `dispersed_low`, C ~ 0.25."""
    return uniform_over([7, 8, 9, 10], n)


def dispersed_low(n):
    return uniform_over([1, 2, 3, 4], n)


def mid_point(n, category=6):
    return point(category, n)


def mid_dispersed(n):
    return uniform_over([5, 6, 7, 8], n)


