def write_panel(panel, subdirectory):
    directory = os.path.join(FIXTURE_ROOT, "scenarios", subdirectory)
    if not os.path.isdir(directory):
        os.makedirs(directory)
    written = []
    for entry in panel:
        path = os.path.join(directory, entry["scenario_id"] + ".json")
        with open(path, "w") as handle:
            json.dump(entry, handle, indent=2, sort_keys=True)
            handle.write("\n")
        written.append(path)
    return written


def main():
    written = write_panel(build_clean_panel(), "clean")
    written += write_panel(build_anchor_panel(), "anchors")
    for path in written:
        print(os.path.relpath(path, FIXTURE_ROOT))
    print("scenarios written: %d" % len(written))


if __name__ == "__main__":
    main()
