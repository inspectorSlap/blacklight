# ---------------------------------------------------------------------------
# Count-vector construction helpers
# ---------------------------------------------------------------------------

def counts(spec, n):
    """Build a count vector from {category: weight} with total exactly n.

    Weights are apportioned by largest remainder so the total is exact and the
    construction is deterministic.
    """
    items = sorted(spec.items())
    total_weight = sum(w for _c, w in items)
    raw = [(c, n * w / float(total_weight)) for c, w in items]
    base = [(c, int(v)) for c, v in raw]
    remainder = n - sum(v for _c, v in base)
    order = sorted(range(len(raw)), key=lambda i: (-(raw[i][1] - base[i][1]),
                                                   raw[i][0]))
    allocated = dict(base)
    for i in order[:remainder]:
        allocated[raw[i][0]] += 1
    vector = [0] * K
    for category, value in allocated.items():
        vector[category - 1] = value
    if sum(vector) != n:
        raise AssertionError("count construction failed for %r at n=%d" % (spec, n))
    return vector


def uniform_over(categories, n):
    return counts({c: 1 for c in categories}, n)


def point(category, n):
    return counts({category: 1}, n)


def specimen(specimen_id, c00, ca0, c0b, cab):
    return {"id": specimen_id,
            "cells": {"00": {"counts": list(c00)}, "A0": {"counts": list(ca0)},
                      "0B": {"counts": list(c0b)}, "AB": {"counts": list(cab)}}}


def repeat_specimens(prefix, builder, how_many):
    """Build a specimen list using CANONICAL frozen-roster identifiers.

    The mapping from role index to identifier is positional and bijective
    (harness/roster.py), so every scenario's meaning is preserved exactly:
    position i still carries the same distribution, which is what the
    leave-one-out order and the first-three/last-three splits depend on. Only
    the label changes.
    """
    naming = roster.semantic_id if prefix == "S" else roster.mechanical_id
    return [specimen(naming(i), *builder(i)) for i in range(how_many)]


def make_light(light_id, semantic, mechanical, validity=None):
    return {"id": light_id,
            "validity": dict(validity or CLEAN_VALIDITY),
            "semantic_specimens": copy.deepcopy(semantic),
            "mechanical_specimens": copy.deepcopy(mechanical)}


def make_payload(lights, analysis_id=None, config=None):
    return {"schema_version": "blackbox.ordinal.ordinal-counts.v0.1",
            "analysis_id": analysis_id,
            "config": copy.deepcopy(config or DEFAULT_CONFIG),
            "lights": lights}


def uniform_payload(analysis_id, semantic, mechanical, validity=None, config=None):
    """Three lights with identical content -- the usual topology-exercise form."""
    lights = [make_light("L%d" % i, semantic, mechanical, validity)
              for i in (1, 2, 3)]
    return make_payload(lights, analysis_id, config)


