"""Deterministic construction of the frozen scenario fixtures.

Every scenario's count vectors are built here from explicit category
specifications -- never sampled -- so the clean panel and the mutant-probe
panel are bit-reproducible. Randomness appears only in the coverage campaign,
whose seeds are recorded separately in `fixtures/seeds.json`.

Expected dispositions in this file are DECLARED by the implementer from the
preregistration's decision rules before the sound reference is run against
them. They are not copied from any target. `harness.checks.panel` then verifies
that the sound reference reproduces every declared expectation; a disagreement
is a finding to adjudicate, not something to overwrite.

Exact point expectations are generated by `harness.oracle`, which is the
independent expected-answer generator, and are additionally cross-checked
against `fixtures/anchors/hand-anchors-v1.0.json`.
"""

